/**
 * Builds the Polaris favicon set into public/:
 *   favicon.svg           modern browsers (scalable)
 *   favicon.ico           16 / 32 / 48 px, for everything else
 *   apple-touch-icon.png  180 px, iPhone / iPad home screen
 *
 *   node scripts/make-favicons.mjs [--preview out.png]
 *
 * The star is a small-size rendering of the Polaris mark
 * (src/components/brand/PolarisLogo.tsx → StarMark): the same eight-point north
 * star, elongated north–south, in the official brand colours. It is redrawn
 * rather than copied because the logo mark relies on thin, semi-transparent,
 * overlapping points that turn to mush below ~48 px — here every facet is a
 * solid shape and nothing overlaps at partial opacity, so it stays crisp at 16 px.
 *
 * Brand colours: #07435E Teal Blue · #4590BA Dodger Blue · #96CBC7 Jamaica Bay
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pub = path.join(root, "public");

// 64-unit grid, centred on (32,32). Lit from the top-left: on each main point
// the facet facing up/left is white, the other Jamaica Bay — the same light and
// shade split the logo gives its points.
const STAR = `
  <polygon points="42.6,21.4 35,32 42.6,42.6 32,35 21.4,42.6 29,32 21.4,21.4 32,29" fill="#4590BA"/>
  <polygon points="32,5 27.5,27.5 32,32"  fill="#FFFFFF"/>
  <polygon points="32,5 36.5,27.5 32,32"  fill="#96CBC7"/>
  <polygon points="54,32 36.5,27.5 32,32" fill="#FFFFFF"/>
  <polygon points="54,32 36.5,36.5 32,32" fill="#96CBC7"/>
  <polygon points="32,59 27.5,36.5 32,32" fill="#FFFFFF"/>
  <polygon points="32,59 36.5,36.5 32,32" fill="#96CBC7"/>
  <polygon points="10,32 27.5,27.5 32,32" fill="#FFFFFF"/>
  <polygon points="10,32 27.5,36.5 32,32" fill="#96CBC7"/>`;

// A gentle top-to-bottom shade around Teal Blue #07435E.
const GRADIENT = `<defs><linearGradient id="t" x1="0" y1="0" x2="0" y2="1">
  <stop offset="0" stop-color="#0A5272"/><stop offset="1" stop-color="#063A52"/>
</linearGradient></defs>`;

// Browser favicon: rounded tile, star near edge-to-edge (favicons need to fill).
const faviconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <!-- Generated by scripts/make-favicons.mjs — edit there, then re-run. -->
  ${GRADIENT}
  <rect width="64" height="64" rx="14" fill="url(#t)"/>${STAR}
</svg>
`;

// iOS rounds the corners itself, so: full-bleed square, star with more margin.
const touchSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-10 -10 84 84">
  ${GRADIENT}
  <rect x="-10" y="-10" width="84" height="84" fill="url(#t)"/>${STAR}
</svg>`;

// Rasterise big, then downscale: much cleaner small sizes than rendering tiny.
async function png(svg, size) {
  const big = await sharp(Buffer.from(svg), { density: 1200 }).resize(1024, 1024).png().toBuffer();
  return sharp(big).resize(size, size, { kernel: "lanczos3" }).png({ compressionLevel: 9 }).toBuffer();
}

// ICO container of PNG images (supported everywhere since Windows Vista).
function ico(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(images.length, 4);
  const dir = Buffer.alloc(16 * images.length);
  let offset = header.length + dir.length;
  images.forEach(({ size, data }, i) => {
    const o = i * 16;
    dir.writeUInt8(size >= 256 ? 0 : size, o);
    dir.writeUInt8(size >= 256 ? 0 : size, o + 1);
    dir.writeUInt16LE(1, o + 4);   // colour planes
    dir.writeUInt16LE(32, o + 6);  // bits per pixel
    dir.writeUInt32LE(data.length, o + 8);
    dir.writeUInt32LE(offset, o + 12);
    offset += data.length;
  });
  return Buffer.concat([header, dir, ...images.map((i) => i.data)]);
}

const icoImages = [];
for (const size of [16, 32, 48]) icoImages.push({ size, data: await png(faviconSvg, size) });

fs.writeFileSync(path.join(pub, "favicon.svg"), faviconSvg);
fs.writeFileSync(path.join(pub, "favicon.ico"), ico(icoImages));
fs.writeFileSync(path.join(pub, "apple-touch-icon.png"), await png(touchSvg, 180));

for (const f of ["favicon.svg", "favicon.ico", "apple-touch-icon.png"]) {
  console.log(f.padEnd(22), fs.statSync(path.join(pub, f)).size, "bytes");
}

